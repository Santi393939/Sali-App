// Writes supabase/seed_reminders.sql from src/content/reminders.ts.
// Run: node --experimental-strip-types scripts/reminders-seed.mjs
// Cards are inserted unverified (verified_by = null), so the app's database
// query hides them until a qualified reviewer fills in verified_by.
import { writeFileSync } from 'node:fs';

const { REMINDERS } = await import('../src/content/reminders.ts');
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const rows = REMINDERS.map(
  (r, i) =>
    `  (${q(r.id)}, ${q(r.kind)}, ${q(r.arabic)}, ${q(r.english)}, ${q(r.sourceRef)}, ${q(r.videoUrl)}, null, true, ${i})`,
);
const sql = `-- Starter reminder cards (drafts awaiting review). Generated by scripts/reminders-seed.mjs.
insert into public.reminders (id, kind, arabic, english, source_ref, video_url, verified_by, published, sort) values
${rows.join(',\n')}
on conflict (id) do update set
  kind = excluded.kind, arabic = excluded.arabic, english = excluded.english,
  source_ref = excluded.source_ref, video_url = excluded.video_url, sort = excluded.sort;
`;
writeFileSync(new URL('../supabase/seed_reminders.sql', import.meta.url), sql);
console.log(`wrote ${REMINDERS.length} reminders`);
